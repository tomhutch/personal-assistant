import logging
import sounddevice as sd
import numpy as np
import threading
import time
from collections import deque
from config import (
    SAMPLE_RATE, 
    WAKE_WORD, 
    WAKE_WORD_MULTIPLIER, 
    COMMAND_MAX_DURATION, 
    COMMAND_SPEECH_MULTIPLIER,
    COMMAND_POST_SPEECH_WINDOW
)
from transcriber import transcribe_audio

logger = logging.getLogger(__name__)

class RollingAudioBuffer:
    def __init__(self, duration_seconds=3.0):
        self.max_samples = int(SAMPLE_RATE * duration_seconds)
        self.buffer = deque()
        self.current_samples = 0
        self.lock = threading.Lock()
        self.total_blocks_received = 0

    def append(self, block):
        with self.lock:
            self.buffer.append(block)
            self.current_samples += len(block)
            self.total_blocks_received += 1
            
            while self.current_samples > self.max_samples and len(self.buffer) > 1:
                removed = self.buffer.popleft()
                self.current_samples -= len(removed)

    def get_audio(self):
        with self.lock:
            if not self.buffer:
                return np.array([], dtype=np.float32)
            return np.concatenate(list(self.buffer), axis=0)

    def clear(self):
        with self.lock:
            self.buffer.clear()
            self.current_samples = 0

def get_audio_rms(block):
    return np.sqrt(np.mean(block**2))

def find_input_device():
    """
    Finds a usable audio input device index by scanning PortAudio devices,
    strictly avoiding raw hardware, loopbacks, and speaker monitor devices.
    """
    try:
        devices = sd.query_devices()
        logger.debug(f"available sounddevice devices: {devices}")
    except Exception:
        logger.error("Failed to query PortAudio devices", exc_info=True)
        return None

    input_devices = [
        (global_idx, dev) for global_idx, dev in enumerate(devices)
        if dev["max_input_channels"] > 0
    ]

    # Priority 1: Non-hardware USB input devices (excluding monitors and loopbacks)
    for idx, dev in input_devices:
        name = dev["name"].lower()
        if (
            "usb" in name 
            and "hw:" not in name 
            and "loopback" not in name 
            and ".monitor" not in name
        ):
            return idx

    # Priority 2: Any non-loopback, non-monitor, non-hardware input device
    for idx, dev in input_devices:
        name = dev["name"].lower()
        if (
            "hw:" not in name 
            and "loopback" not in name 
            and ".monitor" not in name
        ):
            return idx

    return None

def listen_for_wake_word(rolling_buffer):
    """Continuously inspects background buffer, ignoring music/noise hallucinations."""
    logger.info("💤 Listening for wake word ('Hey Susan')... [Adaptive Noise Gate Active]")
    
    noise_floor = 0.001
    last_debug_time = time.time()
    
    # Tags generated by Whisper when background music or noise is present
    IGNORED_TRANSCRIPTS = {"[blank_audio]", "[music]", "[music playing]", "(drumming)", "[applause]", "[laughter]"}
    
    while True:
        now = time.time()
        if now - last_debug_time > 3.0:
            audio_np = rolling_buffer.get_audio()
            logger.debug(
                "Buffer status: %d blocks, length: %.2fs | Noise Floor: %.5f", 
                rolling_buffer.total_blocks_received, 
                len(audio_np) / SAMPLE_RATE,
                noise_floor
            )
            last_debug_time = now

        audio_np = rolling_buffer.get_audio()
        
        if len(audio_np) < SAMPLE_RATE * 2.0:
            time.sleep(0.2)
            continue

        recent_chunk = audio_np[-int(SAMPLE_RATE * 0.5):]
        rms = get_audio_rms(recent_chunk)
        
        if rms < 0.003:
            noise_floor = (0.98 * noise_floor) + (0.02 * rms)
            noise_floor = max(noise_floor, 0.0002)

        relative_threshold = max(noise_floor * WAKE_WORD_MULTIPLIER, 0.0015)
        logger.debug("Live RMS: %.5f | Threshold: %.5f", rms, relative_threshold)
        
        if rms < relative_threshold:
            time.sleep(0.15)
            continue

        logger.debug("🔊 Speech detected! RMS: %.4f (Noise Floor: %.5f, Threshold: %.5f). Submitting to Whisper...", rms, noise_floor, relative_threshold)
        transcript = transcribe_audio(audio_np).lower().strip()
        
        logger.debug("Whisper Output: '%s'", transcript)
        
        # Skip garbage music or blank audio tags so music doesn't trigger false positives
        if transcript in IGNORED_TRANSCRIPTS or not transcript:
            time.sleep(0.2)
            continue
        
        if WAKE_WORD in transcript:
            logger.info("✨ Wake word detected! Transcript: '%s'", transcript)
            rolling_buffer.clear()
            return True, noise_floor
        
        time.sleep(0.3)

def record_utterance(noise_floor):
    """
    Captures command utterance using a lightning-fast, music-proof 
    fixed post-speech window driven by configuration.
    """
    logger.info("🎤 Command mode active. Speak your command...")
    
    speech_threshold = max(noise_floor * COMMAND_SPEECH_MULTIPLIER, 0.003)
    
    chunks = []
    chunk_duration = 0.1  # 100ms blocks
    chunk_samples = int(SAMPLE_RATE * chunk_duration)
    
    speech_detected = False
    post_speech_duration = 0.0
    total_duration = 0.0

    device = find_input_device()
    if device is None:
        logger.error("❌ No usable audio input device found; cannot record utterance.")
        return np.array([], dtype=np.float32)

    with sd.InputStream(device=device, samplerate=SAMPLE_RATE, channels=1, dtype='float32') as stream:
        while total_duration < COMMAND_MAX_DURATION:
            audio_block, _ = stream.read(chunk_samples)
            block = audio_block[:, 0]
            chunks.append(block)
            total_duration += chunk_duration
            
            rms = np.sqrt(np.mean(block**2))
            
            if rms > speech_threshold:
                if not speech_detected:
                    logger.debug("🗣️ Speech confirmed active (RMS: %.5f > Threshold: %.5f)", rms, speech_threshold)
                speech_detected = True
            
            # Uses the configurable post-speech window from config.py
            if speech_detected:
                post_speech_duration += chunk_duration
                if post_speech_duration >= COMMAND_POST_SPEECH_WINDOW:
                    logger.debug("🛑 Capture window complete (%.2fs post-speech).", post_speech_duration)
                    break
                
            if not speech_detected and total_duration >= 3.0:
                logger.debug("⚠️ No speech detected during command window, timing out.")
                break

    if not chunks:
        return np.array([], dtype=np.float32)
    return np.concatenate(chunks, axis=0)